// children: 相邻的静态文本(字面量 + 非响应式字符串/数字表达式)合并成一个 G.t(a + b) ——
// 服务端把它们输出成相邻文本, HTML 解析后是同一个文本节点, hydrate 认领必须一一对应。
func (g *jsGen) children(kids []Expr) string {
	var out []string
	var run []string
	flush := func() {
		if len(run) > 0 {
			out = append(out, "G.t("+strings.Join(run, " + ")+")")
			run = nil
		}
	}
	for _, k := range kids {
		switch x := k.(type) {
		case *JSXText:
			s := normalizeJSXText(x.Text)
			if s == "" {
				continue
			}
			run = append(run, jsQuote(s))
		case *JSXExprChild:
			if x.X == nil {
				continue
			}
			if g.isStaticText(x) {
				run = append(run, "String("+g.expr(x.X)+")")
				continue
			}
			flush()
			out = append(out, g.child(x))
		default:
			flush()
			out = append(out, g.expr(k))
		}
	}
	flush()
	return strings.Join(out, ", ")
}

func (g *jsGen) isStaticText(x *JSXExprChild) bool {
	if x.Reactive {
		return false
	}
	e := x.X
	for {
		p, ok := e.(*Paren)
		if !ok {
			break
		}
		e = p.X
	}
	switch e.(type) {
	case *Binary, *CondExpr, *Call, *JSXElem, *JSXFrag:
		// && / 三元 / map 可能是节点, 交给 child(); 普通调用(如 fmtNumber(x))是文本
		if _, isCall := e.(*Call); !isCall {
			return false
		}
	}
	t := unopt(e.T())
	return t == TString || t == TNumber
}

// child: {expr} 子节点 → 运行时调用
func (g *jsGen) child(x *JSXExprChild) string {
	return g.nodeExpr(x.X, x.Reactive)
}

// nodeExpr: 把节点位置的表达式编成运行时调用, 递归保持嵌套条件/列表的响应式。
// reactive 从外层继承(响应式 cond 的分支里, 内层也要响应式)。
func (g *jsGen) nodeExpr(e Expr, reactive bool) string {
	for {
		p, ok := e.(*Paren)
		if !ok {
			break
		}
		e = p.X
	}
	t := unopt(e.T())
	nodeLike := isNode(t)
	if at, ok := t.(*ArrT); ok && isNode(at.Elem) {
		nodeLike = true
	}
	// 标记(marker)必须与 Go 后端逐一对应: 每个构造用它自己的 .Reactive, 不从外层继承。
	// 递归进入分支时 leaf 文本的 reactive 传 false —— 分支由外层响应式块整体重建, 内部文本是静态的。
	switch y := e.(type) {
	case *Binary:
		if y.Op == "&&" && nodeLike {
			if y.Reactive {
				return "G.cond(() => " + g.expr(y.L) + ", () => " + g.nodeExpr(y.R, false) + ")"
			}
			return "(" + g.expr(y.L) + " && " + g.nodeExpr(y.R, false) + ")"
		}
	case *CondExpr:
		if nodeLike {
			if y.Reactive {
				return "G.cond(() => " + g.expr(y.Test) + ", () => " + g.nodeExpr(y.Then, false) + ", () => " + g.nodeExpr(y.Else, false) + ")"
			}
			return "(" + g.expr(y.Test) + " ? " + g.nodeExpr(y.Then, false) + " : " + g.nodeExpr(y.Else, false) + ")"
		}
	case *Call:
		if m, ok := y.Fn.(*Member); ok && m.Builtin == "map" && y.Reactive {
			return "G.each(() => " + g.expr(m.X) + ", " + g.expr(y.Args[0]) + g.keyFn(y.Args[0]) + ")"
		}
	}
	switch tt := t.(type) {
	case *Prim:
		switch tt {
		case TNode:
			if id, ok := e.(*Ident); ok && id.Sym != nil && id.Sym.Kind == SParam {
				return "G.kids(" + g.expr(e) + ")" // children 可能是 thunk
			}
			return g.expr(e)
		case TString, TNumber, TAny:
			if reactive {
				return "G.text(() => " + g.expr(e) + ")"
			}
			return "G.t(String(" + g.expr(e) + "))"
		case TBool, TUndef:
			return "null"
		}
	case *ArrT:
		if isNode(tt.Elem) {
			return g.expr(e)
		}
		return "G.t(" + g.expr(e) + `.join(""))`
	}
	g.fail(e.GetPos(), "JS backend: cannot use %s as a JSX child", t)
	return ""
}

// keyFn: list.map((x) => <li key={x.id}>…</li>) 的 key 表达式 → ", (x) => x.id"; 没有 key 返回 ""
// 有 key 的列表在客户端按 key 复用/移动 DOM(输入框状态不丢), 没有 key 的整块重建。
func (g *jsGen) keyFn(cb Expr) string {
	a, ok := cb.(*Arrow)
	if !ok {
		return ""
	}
	var root Expr = a.ExprBody
	if root == nil && a.Body != nil && len(a.Body.Stmts) > 0 {
		if r, ok := a.Body.Stmts[len(a.Body.Stmts)-1].(*ReturnStmt); ok {
			root = r.X
		}
	}
	for {
		p, ok := root.(*Paren)
		if !ok {
			break
		}
		root = p.X
	}
	el, ok := root.(*JSXElem)
	if !ok {
		return ""
	}
	for _, at := range el.Attrs {
		if at.Name == "key" && at.Val != nil {
			return ", (" + g.params(a.Params) + ") => " + g.expr(at.Val)
		}
	}
	return ""
}

func (g *jsGen) jsxElem(x *JSXElem) string {
	if x.Comp != nil {
		var ps []string
		for _, a := range x.Attrs {
			if a.Name == "key" {
				continue
			}
			if a.Val == nil {
				ps = append(ps, jsKey(a.Name)+": true")
				continue
			}
			ps = append(ps, jsKey(a.Name)+": "+g.expr(a.Val))
		}
		if len(x.Children) > 0 {
			ps = append(ps, "children: () => ["+g.children(x.Children)+"]")
		}
		return x.Comp.Name + "({ " + strings.Join(ps, ", ") + " })"
	}
	var attrs []string
	for _, a := range x.Attrs {
		if a.Name == "key" {
			continue
		}
		key := jsKey(a.Name)
		if a.Val == nil {
			attrs = append(attrs, key+": true")
			continue
		}
		if _, isStr := a.Val.(*StrLit); isStr || strings.HasPrefix(a.Name, "on") || !a.Reactive {
			attrs = append(attrs, key+": "+g.expr(a.Val))
			continue
		}
		attrs = append(attrs, key+": () => "+g.expr(a.Val))
	}
	as := "null"
	if len(attrs) > 0 {
		as = "{ " + strings.Join(attrs, ", ") + " }"
	}
	kids := g.children(x.Children)
	if kids == "" {
		return "G.el(" + jsQuote(x.Tag) + ", " + as + ")"
	}
	return "G.el(" + jsQuote(x.Tag) + ", " + as + ", () => [" + kids + "])"
}
