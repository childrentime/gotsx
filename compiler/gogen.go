package compiler

// Go 后端: 组件 → Go 函数, JSX → gotsx 节点表达式, hooks → SSR 单趟语义, host:* → 直接调用。

import (
	"fmt"
	"html"
	"strconv"
	"strings"
)

type goGen struct {
	c        *Checker
	m        *Module
	b        strings.Builder
	ind      int
	needHost bool
	hostPkg  string
	tmp      int
	errs     []error
	curRet   Type
	lastMark Pos
}

type genError struct {
	Pos Pos
	Msg string
}

func (e *genError) Error() string { return fmt.Sprintf("%s: %s", e.Pos, e.Msg) }

func (g *goGen) fail(pos Pos, format string, args ...any) {
	panic(&genError{Pos: pos, Msg: fmt.Sprintf(format, args...)})
}

func (g *goGen) line(format string, args ...any) {
	g.b.WriteString(strings.Repeat("\t", g.ind))
	fmt.Fprintf(&g.b, format, args...)
	g.b.WriteByte('\n')
}

func (g *goGen) newTmp() string {
	g.tmp++
	return fmt.Sprintf("_t%d", g.tmp)
}

// mark: 注入 //line 指令, 让下一行 Go 代码的报错/panic 指回 .tsx 源码位置
func (g *goGen) mark(pos Pos) {
	if pos.Line > 0 && pos.File != "" && pos != g.lastMark {
		g.lastMark = pos
		fmt.Fprintf(&g.b, "//line %s:%d\n", pos.File, pos.Line)
	}
}

func stmtPos(s Stmt) Pos {
	switch d := s.(type) {
	case *VarDecl:
		return d.Pos
	case *ReturnStmt:
		return d.Pos
	case *IfStmt:
		return d.Pos
	case *ForOfStmt:
		return d.Pos
	case *ForStmt:
		return d.Pos
	case *WhileStmt:
		return d.Pos
	case *SwitchStmt:
		return d.Pos
	case *BreakStmt:
		return d.Pos
	case *ContinueStmt:
		return d.Pos
	case *ExprStmt:
		return d.Pos
	case *ThrowStmt:
		return d.Pos
	case *TryStmt:
		return d.Pos
	case *Block:
		return d.Pos
	case *FuncDecl:
		return d.Pos
	}
	return Pos{}
}

// GenGo 生成一个模块的 Go 源码
func GenGo(c *Checker, m *Module, pkg, runtimeImport, hostImport string) (src string, err error) {
	g := &goGen{c: c, m: m, hostPkg: "host"}
	defer func() {
		if r := recover(); r != nil {
			if ge, ok := r.(*genError); ok {
				err = ge
				return
			}
			panic(r)
		}
	}()
	var body strings.Builder
	g.genTypes()
	for _, s := range m.Stmts {
		switch d := s.(type) {
		case *FuncDecl:
			if d.Async || (!d.Comp && (clientOnly(d.Body.Stmts) || readsStore(d.Body.Stmts))) {
				continue // 只进 JS 后端(a helper that reads a store has no render context on the server: browser only, like DOM code)
			}
			g.genFunc(d)
		case *VarDecl:
			sym := d.Pat.Sym
			if d.Hook == "createStore" { // the store: its initial value; a page's seed(store, value) overrides it per request
				st := sym.Type.(*StoreT)
				g.mark(d.Pos)
				g.line("var %s = gotsx.NewStore(%q, %s)", sym.Go, sym.Go, g.conv(d.Init.(*Call).Args[0], st.State))
				g.line("")
				continue
			}
			if isNode(sym.Type) {
				g.line("var %s gotsx.Node = %s", sym.Go, g.toNode(d.Init, false))
			} else {
				g.line("var %s %s = %s", sym.Go, g.goType(sym.Type), g.conv(d.Init, sym.Type))
			}
			g.line("")
		}
	}
	body.WriteString(g.b.String())

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by gotsx from %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n\tgotsx %q\n", m.File, pkg, runtimeImport)
	if g.needHost {
		fmt.Fprintf(&out, "\thost %q\n", hostImport)
	}
	out.WriteString(")\n\nvar _ = gotsx.Num\n\n")
	out.WriteString(body.String())
	return out.String(), nil
}

// ---------- 类型 ----------

func (g *goGen) goType(t Type) string {
	switch x := t.(type) {
	case *Prim:
		switch x {
		case TString:
			return "string"
		case TNumber:
			return "float64"
		case TBool:
			return "bool"
		case TNode:
			return "gotsx.Node"
		case TRegExp:
			return "*gotsx.Regex"
		case TVoid:
			return ""
		}
		return "any"
	case *ArrT:
		return "[]" + g.goType(x.Elem)
	case *MapT:
		return "map[string]" + g.goType(x.Val)
	case *ObjT:
		if x.Host && !strings.HasPrefix(x.GoName, "gotsx.") { // framework builtin objects (Meta / Flash) live in the runtime package, not the host
			g.needHost = true
		}
		return x.GoName
	case *OptT:
		return g.goType(x.Elem)
	case *FnT:
		var ps []string
		for _, p := range x.Params {
			ps = append(ps, g.goType(p.Type))
		}
		ret := ""
		if x.Ret != nil && !x.Async {
			ret = g.goType(x.Ret)
		}
		return "func(" + strings.Join(ps, ", ") + ") " + ret
	case *SetterT:
		return "func(any)"
	case *StoreT:
		return "*gotsx.Store[" + g.goType(x.State) + "]"
	}
	return "any"
}

func (g *goGen) zero(t Type) string {
	switch x := unopt(t).(type) {
	case *Prim:
		switch x {
		case TString:
			return `""`
		case TNumber:
			return "0"
		case TBool:
			return "false"
		}
		return "nil"
	case *ObjT:
		return x.GoName + "{}"
	}
	return "nil"
}

func (g *goGen) genTypes() {
	seen := map[*ObjT]bool{}
	emit := func(t *ObjT) {
		if t == nil || seen[t] || t.Host || t.GoName == "" {
			return
		}
		seen[t] = true
		g.line("type %s struct {", t.GoName)
		g.ind++
		for _, f := range t.Fields {
			// 方言对象结构总是带 json tag: 保证 JSON.stringify 用原始键(如 @context), 不受 server/client 影响
			tag := fmt.Sprintf(" `json:%q`", f.Name)
			if isNode(f.Type) {
				tag = " `json:\"-\"`"
			}
			g.line("%s %s%s", f.Go, g.goType(f.Type), tag)
		}
		g.ind--
		g.line("}")
		g.line("")
	}
	for _, s := range g.m.Stmts {
		if d, ok := s.(*InterfaceDecl); ok {
			emit(d.T)
		}
	}
	for _, t := range g.m.AnonTypes {
		emit(t)
	}
}

// ---------- 函数 ----------

func (g *goGen) genFunc(d *FuncDecl) {
	g.mark(d.Pos)
	if d.Comp {
		comp := d.Sym.Comp
		props := comp.Props
		name := d.Sym.Go
		ctxParam := ""
		if g.m.Kind == "client" { // components of client modules render with the request context (store seeds)
			ctxParam = "_ctx *gotsx.Ctx, "
		}
		if g.m.Kind == "client" && d.Default {
			// 岛: 外壳 + 预渲染(the body runs when the island is written, with the context in hand)
			g.line("func %s(props %s) gotsx.Node {", name, props.GoName)
			g.line("\treturn gotsx.Island(%q, props, func(_ctx *gotsx.Ctx) { _ctx.N(%s_ssr(_ctx, props)) })", g.m.Name, name)
			g.line("}")
			g.line("")
			name += "_ssr"
		}
		g.line("func %s(%sprops %s) gotsx.Node {", name, ctxParam, props.GoName)
		g.ind++
		g.curRet = TNode
		if len(d.Params) > 0 {
			g.bindParam(d.Params[0].Pat, "props", props)
		}
		g.stmts(d.Body.Stmts)
		if !endsWithReturn(d.Body) {
			g.line("return nil")
		}
		g.ind--
		g.line("}")
		g.line("")
		return
	}
	ft := d.Sym.Type.(*FnT)
	g.line("func %s(%s) %s {", d.Sym.Go, g.paramList(d.Params, ft), g.goType(ft.Ret))
	g.ind++
	g.bindParams(d.Params, ft)
	saveRet := g.curRet
	g.curRet = ft.Ret
	g.stmts(d.Body.Stmts)
	g.curRet = saveRet
	g.ind--
	g.line("}")
	g.line("")
}

func endsWithReturn(b *Block) bool {
	if len(b.Stmts) == 0 {
		return false
	}
	_, ok := b.Stmts[len(b.Stmts)-1].(*ReturnStmt)
	return ok
}

func (g *goGen) paramList(params []*Param, ft *FnT) string {
	var ps []string
	for i, p := range params {
		name := "p" + strconv.Itoa(i)
		if p.Pat.Kind == PatIdent {
			name = p.Pat.Sym.Go
		}
		ps = append(ps, name+" "+g.goType(ft.Params[i].Type))
	}
	return strings.Join(ps, ", ")
}

// bindParams expands destructured parameters of plain functions (meta({ params }: PageProps) etc.): paramList names them pN, this binds the parts
func (g *goGen) bindParams(params []*Param, ft *FnT) {
	for i, p := range params {
		if p.Pat.Kind != PatIdent {
			g.bindParam(p.Pat, "p"+strconv.Itoa(i), ft.Params[i].Type)
		}
	}
}

// 解构参数: 生成 a := props.A 等
func (g *goGen) bindParam(pat *Pattern, src string, t Type) {
	switch pat.Kind {
	case PatIdent:
		if pat.Sym.Go != src {
			g.line("%s := %s", pat.Sym.Go, src)
			g.line("_ = %s", pat.Sym.Go)
		}
	case PatObject:
		for _, pp := range pat.Props {
			var ft Type = TAny
			access := src
			switch o := unopt(t).(type) {
			case *ObjT:
				f := o.Field(pp.Key)
				access = src + "." + f.Go
				ft = f.Type
				if numConv(f.GoType) {
					access = "float64(" + access + ")"
				}
				if numConvSlice(f.GoType) {
					access = "gotsx.Nums(" + access + ")"
				}
			case *MapT:
				access = src + "[" + strconv.Quote(pp.Key) + "]"
				ft = o.Val
			}
			if pp.Default != nil && pp.Pat.Kind == PatIdent {
				ft = unopt(ft)
				g.line("%s := %s", pp.Pat.Sym.Go, access)
				if def := g.conv(pp.Default, ft); def != g.zero(ft) { // 默认值就是零值的话不用写
					g.line("if %s == %s {", pp.Pat.Sym.Go, g.zero(ft))
					g.line("\t%s = %s", pp.Pat.Sym.Go, def)
					g.line("}")
				}
				g.line("_ = %s", pp.Pat.Sym.Go)
				continue
			}
			g.bindParam(pp.Pat, access, ft)
		}
	case PatArray:
		for i, el := range pat.Elems {
			var et Type = TAny
			if a, ok := unopt(t).(*ArrT); ok {
				et = a.Elem
			}
			g.bindParam(el, fmt.Sprintf("%s[%d]", src, i), et)
		}
	}
}

var numScalars = map[string]bool{"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true, "float32": true}

func numConv(goType string) bool { return numScalars[goType] }

// []int 这类数值切片 → []float64 需要逐元素转换(gotsx.Nums)
func numConvSlice(goType string) bool {
	return strings.HasPrefix(goType, "[]") && numScalars[strings.TrimPrefix(goType, "[]")]
}

// ---------- 语句 ----------

func (g *goGen) stmts(ss []Stmt) {
	for _, s := range ss {
		g.stmt(s)
	}
}

func (g *goGen) block(b *Block) {
	g.ind++
	g.stmts(b.Stmts)
	g.ind--
}

func (g *goGen) stmt(s Stmt) {
	g.mark(stmtPos(s))
	switch d := s.(type) {
	case *VarDecl:
		g.varDecl(d)
	case *ReturnStmt:
		fc := g.fnRet(d)
		if d.X == nil {
			g.line("return")
			return
		}
		if fc == nil || isNode(fc) {
			g.line("return %s", g.toNode(d.X, false))
			return
		}
		if fc == TVoid {
			g.line("%s", g.expr(d.X))
			g.line("return")
			return
		}
		g.line("return %s", g.conv(d.X, fc))
	case *IfStmt:
		g.line("if %s {", g.truthy(d.Cond))
		g.block(d.Then)
		if d.Else != nil {
			switch e := d.Else.(type) {
			case *Block:
				g.line("} else {")
				g.block(e)
			case *IfStmt:
				g.line("} else {")
				g.ind++
				g.stmt(e)
				g.ind--
			}
		}
		g.line("}")
	case *ForOfStmt:
		if d.Pat.Kind == PatIdent {
			g.line("for _, %s := range %s {", d.Pat.Sym.Go, g.expr(d.Iter))
			g.ind++
			g.line("_ = %s", d.Pat.Sym.Go)
			g.ind--
		} else {
			tmp := g.newTmp()
			g.line("for _, %s := range %s {", tmp, g.expr(d.Iter))
			g.ind++
			g.bindParam(d.Pat, tmp, d.Pat.T)
			g.ind--
		}
		g.block(d.Body)
		g.line("}")
	case *WhileStmt:
		g.line("for %s {", g.truthy(d.Cond))
		g.block(d.Body)
		g.line("}")
	case *ForStmt:
		g.forStmt(d)
	case *BreakStmt:
		g.line("break")
	case *ContinueStmt:
		g.line("continue")
	case *SwitchStmt:
		g.switchStmt(d)
	case *ExprStmt:
		g.exprStmt(d.X)
	case *Block:
		g.line("{")
		g.block(d)
		g.line("}")
	case *TryStmt:
		g.stmts(d.Body.Stmts)
		if d.Finally != nil {
			g.stmts(d.Finally.Stmts)
		}
	case *ThrowStmt:
		g.line("gotsx.Throw(%s)", g.expr(d.X))
	case *FuncDecl:
		ft := d.Sym.Type.(*FnT)
		if d.Async || clientOnly(d.Body.Stmts) {
			g.line("%s := %s", d.Sym.Go, g.stub(ft, strings.Split(g.paramList(d.Params, ft), ", ")))
			g.line("_ = %s", d.Sym.Go)
			return
		}
		g.line("%s := func(%s) %s {", d.Sym.Go, g.paramList(d.Params, ft), g.goType(ft.Ret))
		g.ind++
		g.bindParams(d.Params, ft)
		g.ind--
		saveRet := g.curRet
		g.curRet = ft.Ret
		g.block(d.Body)
		g.curRet = saveRet
		g.line("}")
		g.line("_ = %s", d.Sym.Go)
	case *InterfaceDecl, *TypeAlias, *EmptyStmt:
	default:
		g.fail(Pos{}, "Go backend: unsupported statement %T", s)
	}
}

// 当前函数的返回类型(通过 ReturnStmt 表达式的期望推断不了时用 nil)
func (g *goGen) fnRet(r *ReturnStmt) Type {
	return g.curRet
}

func (g *goGen) exprStmt(x Expr) {
	switch e := x.(type) {
	case *Call:
		if e.Kind == "hook:useEffect" || e.Kind == "hook:useEffectOnce" || e.Kind == "storeSet" || containsAwait(e) {
			return
		}
		if e.Kind == "host" && e.Host.Throws && e.Host.Ret == nil {
			g.line("gotsx.Check(%s)", g.hostCall(e, true))
			return
		}
		g.line("%s", g.expr(e))
	case *Assign:
		g.line("%s", g.assign(e))
	case *Update:
		g.line("%s", g.update(e))
	case *Unary:
		if e.Op == "delete" {
			g.line("%s", g.deleteKey(e))
			return
		}
		g.line("_ = %s", g.expr(x))
	case *AwaitExpr:
		return
	default:
		g.line("_ = %s", g.expr(x))
	}
}

// deleteKey: delete m[k] / delete m.k → delete(m, k)
func (g *goGen) deleteKey(e *Unary) string {
	switch t := e.X.(type) {
	case *Index:
		return "delete(" + g.expr(t.X) + ", " + g.expr(t.I) + ")"
	case *Member:
		return "delete(" + g.expr(t.X) + ", " + strconv.Quote(t.Name) + ")"
	}
	g.fail(e.Pos, "delete only works on a Record key")
	return ""
}

// simpleStmt: for 的 init / post 位置(Go 只接受简单语句)
func (g *goGen) simpleStmt(x Expr) string {
	switch e := x.(type) {
	case *Assign:
		return g.assign(e)
	case *Update:
		return g.update(e)
	case *Paren:
		return g.simpleStmt(e.X)
	}
	return g.expr(x)
}

func (g *goGen) forStmt(d *ForStmt) {
	init, post := "", ""
	var loopVar *Symbol
	if d.Init != nil {
		switch i := d.Init.(type) {
		case *VarDecl:
			loopVar = i.Pat.Sym
			v := g.zero(loopVar.Type)
			if i.Init != nil {
				v = g.conv(i.Init, loopVar.Type)
			}
			if isNumber(loopVar.Type) {
				v = "float64(" + v + ")" // 字面量 0 会被 Go 推成 int
			}
			init = loopVar.Go + " := " + v
		case *ExprStmt:
			init = g.simpleStmt(i.X)
		}
	}
	cond := ""
	if d.Cond != nil {
		cond = g.truthy(d.Cond)
	}
	if d.Update != nil {
		post = g.simpleStmt(d.Update)
	}
	g.line("for %s; %s; %s {", init, cond, post)
	if loopVar != nil {
		g.ind++
		g.line("_ = %s", loopVar.Go)
		g.ind--
	}
	g.block(d.Body)
	g.line("}")
}

// switchStmt: JS 的 switch 默认贯穿, Go 默认不贯穿 —— 空 case 合并成 case a, b:, 没有 break/return 结尾的补 fallthrough
func (g *goGen) switchStmt(d *SwitchStmt) {
	dt := d.Disc.T()
	g.line("switch %s {", g.expr(d.Disc))
	var pending []string
	hasDefault := false
	for idx, cs := range d.Cases {
		last := idx == len(d.Cases)-1
		if cs.Test == nil {
			hasDefault = true
		} else {
			pending = append(pending, g.conv(cs.Test, unopt(dt)))
		}
		if len(cs.Body) == 0 && !last {
			continue // 空 case: 与下一个合并
		}
		if hasDefault {
			g.line("default:")
		} else {
			g.line("case %s:", strings.Join(pending, ", "))
		}
		pending, hasDefault = nil, false
		body := cs.Body
		jump := false
		if n := len(body); n > 0 {
			switch body[n-1].(type) {
			case *BreakStmt:
				body = body[:n-1] // Go 的 case 自带 break
				jump = true
			case *ReturnStmt, *ThrowStmt, *ContinueStmt:
				jump = true
			}
		}
		g.ind++
		g.stmts(body)
		if !jump && !last {
			g.line("fallthrough")
		}
		g.ind--
	}
	g.line("}")
}

// assign: x = v / x += v, 目标可以是变量 / 字段 / Record 键 / 数组下标
func (g *goGen) assign(e *Assign) string {
	lhs, goType := g.lvalue(e.Target)
	if e.Op == "=" {
		v := g.conv(e.Val, e.Target.T())
		if numConv(goType) {
			v = goType + "(" + v + ")"
		}
		return lhs + " = " + v
	}
	op := strings.TrimSuffix(e.Op, "=")
	if numConv(goType) { // 宿主的 int 字段: 转成 float64 算再转回去
		return fmt.Sprintf("%s = %s(float64(%s) %s (%s))", lhs, goType, lhs, op, g.expr(e.Val))
	}
	if op == "%" {
		return fmt.Sprintf("%s = gotsx.Mod(%s, %s)", lhs, lhs, g.expr(e.Val))
	}
	if op == "+" && isString(e.Target.T()) {
		return lhs + " += " + g.strOf(e.Val)
	}
	return lhs + " " + e.Op + " " + g.expr(e.Val)
}

// update: x++ / x-- 作为语句
func (g *goGen) update(e *Update) string {
	lhs, goType := g.lvalue(e.X)
	if numConv(goType) {
		return fmt.Sprintf("%s = %s(float64(%s) %s 1)", lhs, goType, lhs, string(e.Op[0]))
	}
	return lhs + e.Op
}

// lvalue: 可赋值位置的 Go 表达式 + 宿主字段的原始 Go 类型(数值转换用)
func (g *goGen) lvalue(e Expr) (string, string) {
	switch x := e.(type) {
	case *Paren:
		return g.lvalue(x.X)
	case *Ident:
		return g.ident(x), ""
	case *Member:
		switch t := unopt(x.X.T()).(type) {
		case *ObjT:
			if f := t.Field(x.Name); f != nil {
				return g.expr(x.X) + "." + f.Go, f.GoType
			}
		case *MapT:
			return g.expr(x.X) + "[" + strconv.Quote(x.Name) + "]", ""
		}
	case *Index:
		switch unopt(x.X.T()).(type) {
		case *ArrT:
			return g.expr(x.X) + "[int(" + g.expr(x.I) + ")]", ""
		case *MapT:
			return g.expr(x.X) + "[" + g.expr(x.I) + "]", ""
		}
	}
	g.fail(e.GetPos(), "Go backend: cannot assign to this expression")
	return "", ""
}

// addr: push/pop/splice 需要数组的地址(&xs)
func (g *goGen) addr(e Expr) string {
	switch x := e.(type) {
	case *Paren:
		return g.addr(x.X)
	case *Ident:
		return "&" + g.ident(x)
	case *Member:
		if t, ok := unopt(x.X.T()).(*ObjT); ok {
			if f := t.Field(x.Name); f != nil {
				if numConvSlice(f.GoType) {
					g.fail(x.Pos, "a host numeric-array field is a converted copy and cannot be mutated in place; copy it into a variable first")
				}
				return "&" + g.expr(x.X) + "." + f.Go
			}
		}
		if _, ok := unopt(x.X.T()).(*MapT); ok {
			g.fail(x.Pos, "an array inside a Record cannot be mutated in place (Go map elements are not addressable); read it into a variable first")
		}
	case *Index:
		if _, ok := unopt(x.X.T()).(*ArrT); ok {
			return "&" + g.expr(x.X) + "[int(" + g.expr(x.I) + ")]"
		}
		g.fail(x.Pos, "an array inside a Record cannot be mutated in place (Go map elements are not addressable); read it into a variable first")
	}
	g.fail(e.GetPos(), "in-place mutation needs a variable / field / index")
	return ""
}

var clientOnlyGlobals = map[string]bool{"fetch": true, "setTimeout": true, "clearTimeout": true, "setInterval": true, "clearInterval": true,
	"emit": true, "on": true, "alert": true, "confirm": true, "requestAnimationFrame": true}

// clientOnly: 表达式/语句里是否用到了只有浏览器才有的东西(document、localStorage、fetch、await…)
func clientOnly(n any) bool {
	found := false
	var walkS func(s Stmt)
	var walkE func(e Expr)
	walkE = func(e Expr) {
		walkExpr(e, func(x Expr) bool {
			if found {
				return false
			}
			switch y := x.(type) {
			case *AwaitExpr:
				found = true
			case *Ident:
				if y.Sym != nil && y.Sym.Kind == SBuiltin && (y.Sym.Type == TAny || clientOnlyGlobals[y.Sym.Name]) {
					found = true
				}
			case *Call:
				if y.Kind == "storeSet" {
					found = true
				}
			case *Arrow:
				if y.Body != nil {
					for _, s := range y.Body.Stmts {
						walkS(s)
					}
				}
			}
			return !found
		})
	}
	walkS = func(s Stmt) {
		if found || s == nil {
			return
		}
		switch d := s.(type) {
		case *VarDecl:
			walkE(d.Init)
		case *ReturnStmt:
			walkE(d.X)
		case *ExprStmt:
			walkE(d.X)
		case *ThrowStmt:
			walkE(d.X)
		case *IfStmt:
			walkE(d.Cond)
			walkS(d.Then)
			walkS(d.Else)
		case *ForOfStmt:
			walkE(d.Iter)
			walkS(d.Body)
		case *ForStmt:
			walkS(d.Init)
			walkE(d.Cond)
			walkE(d.Update)
			walkS(d.Body)
		case *WhileStmt:
			walkE(d.Cond)
			walkS(d.Body)
		case *SwitchStmt:
			walkE(d.Disc)
			for _, cs := range d.Cases {
				walkE(cs.Test)
				for _, x := range cs.Body {
					walkS(x)
				}
			}
		case *Block:
			for _, x := range d.Stmts {
				walkS(x)
			}
		case *TryStmt:
			walkS(d.Body)
			walkS(d.Catch)
			walkS(d.Finally)
		case *FuncDecl:
			if d.Async {
				found = true
			} else {
				walkS(d.Body)
			}
		}
	}
	switch x := n.(type) {
	case Expr:
		walkE(x)
	case Stmt:
		walkS(x)
	case []Stmt:
		for _, s := range x {
			walkS(s)
		}
	}
	return found
}

// readsStore: does a module-level helper read a store (cart.count / const { count } = cart)? On the server only
// components carry the render context that holds the request's seed, so such a helper is browser-only (Go gets
// no definition: calling it during a render fails at go build with the .tsx line, like a DOM helper).
func readsStore(stmts []Stmt) bool {
	found := false
	var walkS func(s Stmt)
	walkE := func(e Expr) {
		walkExpr(e, func(x Expr) bool {
			if found {
				return false
			}
			switch y := x.(type) {
			case *Member:
				if _, ok := y.X.T().(*StoreT); ok && y.Name != "set" {
					found = true
				}
			case *Arrow:
				if y.Body != nil {
					for _, s := range y.Body.Stmts {
						walkS(s)
					}
				}
			}
			return !found
		})
	}
	walkS = func(s Stmt) {
		if found || s == nil {
			return
		}
		switch d := s.(type) {
		case *VarDecl:
			if d.Init != nil && d.Pat.Kind == PatObject {
				if _, isStore := d.Init.T().(*StoreT); isStore { // const { count } = cart
					found = true
					return
				}
			}
			walkE(d.Init)
		case *ReturnStmt:
			walkE(d.X)
		case *ExprStmt:
			walkE(d.X)
		case *ThrowStmt:
			walkE(d.X)
		case *IfStmt:
			walkE(d.Cond)
			walkS(d.Then)
			walkS(d.Else)
		case *ForOfStmt:
			walkE(d.Iter)
			walkS(d.Body)
		case *ForStmt:
			walkS(d.Init)
			walkE(d.Cond)
			walkE(d.Update)
			walkS(d.Body)
		case *WhileStmt:
			walkE(d.Cond)
			walkS(d.Body)
		case *SwitchStmt:
			walkE(d.Disc)
			for _, cs := range d.Cases {
				walkE(cs.Test)
				for _, x := range cs.Body {
					walkS(x)
				}
			}
		case *Block:
			for _, x := range d.Stmts {
				walkS(x)
			}
		case *TryStmt:
			walkS(d.Body)
			walkS(d.Catch)
			walkS(d.Finally)
		case *FuncDecl:
			walkS(d.Body)
		}
	}
	for _, s := range stmts {
		walkS(s)
	}
	return found
}

func (g *goGen) stub(ft *FnT, params []string) string {
	body := "{}"
	if ft.Ret != nil && ft.Ret != TVoid && !ft.Async {
		body = "{ return " + g.zero(ft.Ret) + " }"
	}
	ret := ""
	if !ft.Async {
		ret = g.goType(ft.Ret)
	}
	return "func(" + strings.Join(params, ", ") + ") " + ret + " " + body
}

func containsAwait(e Expr) bool {
	found := false
	walkExpr(e, func(x Expr) bool {
		if _, ok := x.(*AwaitExpr); ok {
			found = true
		}
		_, isArrow := x.(*Arrow)
		return !isArrow && !found
	})
	return found
}

func (g *goGen) varDecl(d *VarDecl) {
	switch d.Hook {
	case "useState":
		call := d.Init.(*Call)
		n, set := d.Pat.Elems[0].Sym, d.Pat.Elems[1].Sym
		g.line("var %s %s = %s", n.Go, g.goType(d.Pat.T), g.conv(call.Args[0], d.Pat.T))
		g.line("_ = %s", n.Go)
		g.line("%s := func(any) {}", set.Go)
		g.line("_ = %s", set.Go)
		return
	case "memo":
		if call, ok := d.Init.(*Call); ok && call.Kind == "hook:useMemo" {
			g.line("var %s %s = (%s)()", d.Pat.Sym.Go, g.goType(d.Pat.T), g.expr(call.Args[0]))
			g.line("_ = %s", d.Pat.Sym.Go)
			return
		}
	}
	if d.Pat.Kind == PatIdent {
		sym := d.Pat.Sym
		gt := g.goType(sym.Type)
		if d.Init == nil {
			g.line("var %s %s", sym.Go, gt)
		} else if containsAwait(d.Init) {
			g.line("var %s %s", sym.Go, gt)
		} else if isNode(sym.Type) {
			g.line("var %s gotsx.Node = %s", sym.Go, g.toNode(d.Init, false))
		} else {
			g.line("var %s %s = %s", sym.Go, gt, g.conv(d.Init, sym.Type))
		}
		g.line("_ = %s", sym.Go)
		return
	}
	tmp := g.newTmp()
	if st, ok := d.Init.T().(*StoreT); ok { // const { count } = cart: the request's value of the store
		g.line("%s := %s.Get(_ctx)", tmp, g.expr(d.Init))
		g.line("_ = %s", tmp)
		g.bindParam(d.Pat, tmp, st.State)
		return
	}
	g.line("%s := %s", tmp, g.expr(d.Init))
	g.line("_ = %s", tmp)
	g.bindParam(d.Pat, tmp, d.Init.T())
}

