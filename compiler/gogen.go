// conv: 表达式转成期望类型的 Go 表达式
func (g *goGen) conv(e Expr, want Type) string {
	if _, ok := e.(*NullLit); ok && want != nil {
		return g.zero(want)
	}
	if want != nil && isNode(want) {
		return g.toNode(e, false)
	}
	if want != nil && isString(want) && isNumber(e.T()) {
		return "gotsx.Num(" + g.expr(e) + ")"
	}
	return g.expr(e)
}

func (g *goGen) strOf(e Expr) string {
	t := unopt(e.T())
	switch {
	case isString(t):
		return g.expr(e)
	case isNumber(t):
		return "gotsx.Num(" + g.expr(e) + ")"
	}
	return "gotsx.Str(" + g.expr(e) + ")"
}

func (g *goGen) truthy(e Expr) string {
	if p, ok := e.(*Paren); ok {
		return g.truthy(p.X)
	}
	if u, ok := e.(*Unary); ok && u.Op == "!" {
		return "!(" + g.truthy(u.X) + ")"
	}
	if o, ok := e.T().(*OptT); ok { // 可能缺席的对象(如 find 的结果): 零值即 undefined
		if _, isObj := o.Elem.(*ObjT); isObj {
			return "gotsx.NonZero(" + g.expr(e) + ")"
		}
	}
	t := unopt(e.T())
	switch x := t.(type) {
	case *Prim:
		switch x {
		case TBool:
			return g.expr(e)
		case TString:
			return "(" + g.expr(e) + ` != "")`
		case TNumber:
			return "(" + g.expr(e) + " != 0)"
		case TNode:
			return "(" + g.expr(e) + " != nil)"
		case TUndef:
			return "false"
		}
	case *ArrT, *ObjT, *MapT, *FnT:
		return "true"
	}
	return "gotsx.Truthy(" + g.expr(e) + ")"
}

func (g *goGen) expr(e Expr) string {
	switch x := e.(type) {
	case *Ident:
		return g.ident(x)
	case *NumLit:
		return x.Raw
	case *StrLit:
		return strconv.Quote(x.Val)
	case *BoolLit:
		if x.Val {
			return "true"
		}
		return "false"
	case *RegexLit:
		return "gotsx.Re(" + strconv.Quote(goRegex(x.Pattern, x.Flags)) + ", " + strconv.Quote(x.Flags) + ")"
	case *NullLit:
		return "nil"
	case *TemplateLit:
		var parts []string
		for i, q := range x.Quasis {
			if q != "" {
				parts = append(parts, strconv.Quote(q))
			}
			if i < len(x.Exprs) {
				parts = append(parts, g.strOf(x.Exprs[i]))
			}
		}
		if len(parts) == 0 {
			return `""`
		}
		return strings.Join(parts, " + ")
	case *ArrayLit:
		return g.arrayLit(x)
	case *ObjectLit:
		if mt, ok := unopt(x.T()).(*MapT); ok {
			var fs []string
			for _, p := range x.Props {
				if p.Spread != nil {
					g.fail(x.Pos, "Go backend: object spread is not supported")
				}
				fs = append(fs, strconv.Quote(p.Key)+": "+g.conv(p.Val, mt.Val))
			}
			return "map[string]" + g.goType(mt.Val) + "{" + strings.Join(fs, ", ") + "}"
		}
		o, ok := unopt(x.T()).(*ObjT)
		if !ok {
			g.fail(x.Pos, "cannot determine the type of the object literal")
		}
		var fs []string
		for _, p := range x.Props {
			if p.Spread != nil {
				g.fail(x.Pos, "Go backend: object spread is not supported")
			}
			f := o.Field(p.Key)
			fs = append(fs, f.Go+": "+g.conv(p.Val, f.Type))
		}
		return o.GoName + "{" + strings.Join(fs, ", ") + "}"
	case *Member:
		return g.member(x)
	case *Index:
		xt := unopt(x.X.T())
		switch xt.(type) {
		case *ArrT:
			return "gotsx.At(" + g.expr(x.X) + ", " + g.expr(x.I) + ")" // JS 语义: 越界零值
		case *MapT:
			return g.expr(x.X) + "[" + g.expr(x.I) + "]"
		}
		if isString(xt) {
			return "gotsx.CharAt(" + g.expr(x.X) + ", " + g.expr(x.I) + ")"
		}
		g.fail(x.Pos, "Go backend: cannot index into %s", xt)
	case *Call:
		return g.call(x)
	case *Unary:
		switch x.Op {
		case "!":
			return "!(" + g.truthy(x.X) + ")"
		case "-", "+":
			return x.Op + g.expr(x.X)
		case "delete":
			return "func() bool { " + g.deleteKey(x) + "; return true }()"
		}
		g.fail(x.Pos, "Go backend: %s is not supported", x.Op)
	case *Binary:
		return g.binary(x)
	case *CondExpr:
		t := x.T()
		if isNode(t) {
			s := fmt.Sprintf("func() gotsx.Node { if %s { return %s }; return %s }()", g.truthy(x.Test), g.toNode(x.Then, false), g.toNode(x.Else, false))
			if x.Reactive {
				return "gotsx.Marked(" + s + ")"
			}
			return s
		}
		return fmt.Sprintf("func() %s { if %s { return %s }; return %s }()", g.goType(t), g.truthy(x.Test), g.conv(x.Then, t), g.conv(x.Else, t))
	case *Arrow:
		return g.arrow(x)
	case *Assign:
		g.fail(x.Pos, "Go backend: assignment in expression position is not supported")
	case *Update:
		id, ok := x.X.(*Ident)
		if !ok {
			g.fail(x.Pos, "%s as an expression only works on a variable (or write it as a standalone statement)", x.Op)
		}
		name := g.ident(id)
		if x.Prefix {
			return fmt.Sprintf("func() float64 { %s%s; return %s }()", name, x.Op, name)
		}
		return fmt.Sprintf("func() float64 { v := %s; %s%s; return v }()", name, name, x.Op)
	case *AsExpr:
		return g.expr(x.X)
	case *AwaitExpr:
		g.fail(x.Pos, "await can only be used in client code")
	case *NonNull:
		return g.expr(x.X)
	case *Paren:
		return "(" + g.expr(x.X) + ")"
	case *JSXElem, *JSXFrag:
		return g.toNode(e, false)
	case *SpreadExpr:
		return g.expr(x.X)
	}
	g.fail(e.GetPos(), "Go backend: unsupported expression %T", e)
	return ""
}

func (g *goGen) ident(x *Ident) string {
	s := x.Sym
	if s == nil {
		g.fail(x.Pos, "unresolved identifier %s", x.Name)
	}
	switch s.Kind {
	case SHostMember:
		g.needHost = true
		return s.Go
	case SComp:
		g.fail(x.Pos, "component %s cannot be used as a value", x.Name)
	case SBuiltin:
		g.fail(x.Pos, "%s can only be used in client code", x.Name)
	}
	return s.Go
}

func (g *goGen) arrayLit(x *ArrayLit) string {
	at, ok := unopt(x.T()).(*ArrT)
	if !ok {
		g.fail(x.Pos, "cannot determine the array type")
	}
	et := g.goType(at.Elem)
	var parts []string
	var cur []string
	flush := func() {
		if len(cur) > 0 {
			parts = append(parts, "[]"+et+"{"+strings.Join(cur, ", ")+"}")
			cur = nil
		}
	}
	for _, el := range x.Elems {
		if sp, ok := el.(*SpreadExpr); ok {
			flush()
			parts = append(parts, g.expr(sp.X))
			continue
		}
		cur = append(cur, g.conv(el, at.Elem))
	}
	flush()
	if len(parts) == 0 {
		return "[]" + et + "{}"
	}
	out := parts[0]
	for _, p := range parts[1:] {
		out = "gotsx.Concat(" + out + ", " + p + ")"
	}
	return out
}

func (g *goGen) member(x *Member) string {
	xt := unopt(x.X.T())
	switch t := xt.(type) {
	case *ArrT:
		if x.Name == "length" {
			return "float64(len(" + g.expr(x.X) + "))"
		}
	case *Prim:
		if t == TString && x.Name == "length" {
			return "gotsx.StrLen(" + g.expr(x.X) + ")"
		}
	case *ObjT:
		f := t.Field(x.Name)
		if f != nil {
			s := g.expr(x.X) + "." + f.Go
			if numConv(f.GoType) {
				return "float64(" + s + ")"
			}
			if numConvSlice(f.GoType) {
				return "gotsx.Nums(" + s + ")"
			}
			return s
		}
		return g.expr(x.X) + "." + x.GoName // 宿主方法, 由 call 处理
	case *MapT:
		return g.expr(x.X) + "[" + strconv.Quote(x.Name) + "]"
	case *HostModT:
		g.needHost = true
		return t.Go + "." + x.GoName
	case *StoreT:
		if x.Name == "set" {
			g.fail(x.Pos, "%s.set can only be used in client code", t.Sym.Name)
		}
		f := t.State.Field(x.Name)
		s := g.expr(x.X) + ".Get(_ctx)." + f.Go
		if numConv(f.GoType) {
			return "float64(" + s + ")"
		}
		if numConvSlice(f.GoType) {
			return "gotsx.Nums(" + s + ")"
		}
		return s
	}
	g.fail(x.Pos, "Go backend: %s has no accessible member %s", xt, x.Name)
	return ""
}

func (g *goGen) call(x *Call) string {
	switch {
	case x.Kind == "host":
		return g.hostCall(x, false)
	case strings.HasPrefix(x.Kind, "builtin:"):
		return g.builtinCall(x)
	case strings.HasPrefix(x.Kind, "global:"):
		name := strings.TrimPrefix(x.Kind, "global:")
		arg := func() string { return g.expr(x.Args[0]) }
		switch name {
		case "String":
			return "gotsx.Str(" + arg() + ")"
		case "Number", "parseInt", "parseFloat":
			return "gotsx.ToNum(" + arg() + ")"
		case "Boolean":
			return g.truthy(x.Args[0])
		case "encodeURIComponent":
			return "gotsx.EncodeURIComponent(" + arg() + ")"
		case "decodeURIComponent":
			return "gotsx.DecodeURIComponent(" + arg() + ")"
		case "isNaN":
			return "gotsx.IsNaN(" + arg() + ")"
		case "jsonLd":
			return "gotsx.LdScript(" + arg() + ")"
		case "t":
			return "gotsx.Tr(" + g.expr(x.Args[0]) + ", " + g.expr(x.Args[1]) + ")"
		case "tv":
			return "gotsx.Trv(" + g.expr(x.Args[0]) + ", " + g.expr(x.Args[1]) + ", " + g.expr(x.Args[2]) + ")"
		case "plural":
			return "gotsx.Plural(" + g.expr(x.Args[0]) + ", " + g.expr(x.Args[1]) + ", " + g.expr(x.Args[2]) + ")"
		case "fmtNum":
			return "gotsx.FmtNum(" + g.expr(x.Args[0]) + ", " + g.expr(x.Args[1]) + ")"
		case "fmtCur":
			return "gotsx.FmtCur(" + g.expr(x.Args[0]) + ", " + g.expr(x.Args[1]) + ")"
		case "fmtDate":
			return "gotsx.FmtDate(" + g.expr(x.Args[0]) + ", " + g.expr(x.Args[1]) + ")"
		case "lpath":
			return "gotsx.LPath(" + g.expr(x.Args[0]) + ", " + g.expr(x.Args[1]) + ")"
		case "isoDate":
			return "gotsx.IsoDate(" + arg() + ")"
		case "redirect":
			code := "302"
			if len(x.Args) == 2 {
				code = g.expr(x.Args[1])
			}
			return "gotsx.Redirect(" + arg() + ", " + code + ")"
		case "notFound":
			return "gotsx.NotFound()"
		case "seed":
			st := x.Args[0].T().(*StoreT)
			return "gotsx.Seed(props, " + g.expr(x.Args[0]) + ", " + g.conv(x.Args[1], st.State) + ")"
		}
		g.fail(x.Pos, "%s can only be used in client code", name)
	case x.Kind == "storeSet":
		g.fail(x.Pos, "store.set can only be used in client code (an event handler, effect or plain function)")
	case x.Kind == "setter":
		return g.expr(x.Fn) + "(" + g.expr(x.Args[0]) + ")"
	case x.Kind == "hook:useMemo":
		return "(" + g.expr(x.Args[0]) + ")()"
	case x.Kind == "fn":
		ft, _ := unopt(x.Fn.T()).(*FnT)
		var args []string
		for i, a := range x.Args {
			var want Type
			if ft != nil && i < len(ft.Params) {
				want = ft.Params[i].Type
			}
			args = append(args, g.conv(a, want))
		}
		return g.expr(x.Fn) + "(" + strings.Join(args, ", ") + ")"
	}
	g.fail(x.Pos, "Go backend: cannot compile this call (%s)", x.Kind)
	return ""
}

func (g *goGen) hostCall(x *Call, stmt bool) string {
	m := x.Host
	var callee string
	switch f := x.Fn.(type) {
	case *Ident:
		callee = g.ident(f)
	case *Member:
		callee = g.member(f)
	default:
		g.fail(x.Pos, "unsupported host call form")
	}
	g.needHost = true
	var args []string
	for i, a := range x.Args {
		s := g.conv(a, m.Params[i].Type)
		if numConv(m.Params[i].Go) {
			s = m.Params[i].Go + "(" + s + ")"
		}
		args = append(args, s)
	}
	call := callee + "(" + strings.Join(args, ", ") + ")"
	if stmt {
		return call
	}
	if m.Throws {
		call = "gotsx.Must(" + call + ")"
	}
	if numConv(m.GoRet) {
		call = "float64(" + call + ")"
	}
	if numConvSlice(m.GoRet) {
		call = "gotsx.Nums(" + call + ")"
	}
	return call
}

func (g *goGen) builtinCall(x *Call) string {
	name := strings.TrimPrefix(x.Kind, "builtin:")
	mem := x.Fn.(*Member)
	recv := ""
	if _, isGlobal := unopt(mem.X.T()).(*GlobalT); !isGlobal {
		recv = g.expr(mem.X) // console/JSON/Math 是命名空间, 不能当值求值
	}
	arg := func(i int) string {
		if i < len(x.Args) {
			return g.expr(x.Args[i])
		}
		return ""
	}
	rt := unopt(mem.X.T())
	switch r := rt.(type) {
	case *ArrT:
		switch name {
		case "map":
			if a, ok := x.Args[0].(*Arrow); ok && len(a.Params) == 2 {
				return "gotsx.MapI(" + recv + ", " + g.expr(x.Args[0]) + ")"
			}
			if a, ok := x.Args[0].(*Arrow); ok && len(a.Params) == 0 {
				ret := "gotsx.Node"
				if at, ok := unopt(x.T()).(*ArrT); ok {
					ret = g.goType(at.Elem)
				}
				return "gotsx.Map(" + recv + ", func(_ " + g.goType(r.Elem) + ") " + ret + " { return (" + g.expr(x.Args[0]) + ")() })"
			}
			return "gotsx.Map(" + recv + ", " + g.expr(x.Args[0]) + ")"
		case "filter", "find", "some", "every", "forEach", "findIndex":
			suffix := ""
			if a, ok := x.Args[0].(*Arrow); ok && len(a.Params) == 2 {
				suffix = "I"
			}
			return "gotsx." + strings.ToUpper(name[:1]) + name[1:] + suffix + "(" + recv + ", " + arg(0) + ")"
		case "lastIndexOf":
			return "gotsx.LastIndexOf(" + recv + ", " + g.conv(x.Args[0], r.Elem) + ")"
		case "push", "unshift":
			var as []string
			for _, a := range x.Args {
				as = append(as, g.conv(a, r.Elem))
			}
			return "gotsx." + strings.ToUpper(name[:1]) + name[1:] + "(" + g.addr(mem.X) + ", " + strings.Join(as, ", ") + ")"
		case "pop", "shift":
			return "gotsx." + strings.ToUpper(name[:1]) + name[1:] + "(" + g.addr(mem.X) + ")"
		case "splice":
			del := "-1" // 省略 deleteCount = 删到末尾
			if len(x.Args) > 1 {
				del = arg(1)
			}
			as := []string{g.addr(mem.X), arg(0), del}
			if len(x.Args) > 2 {
				for _, a := range x.Args[2:] {
					as = append(as, g.conv(a, r.Elem))
				}
			}
			return "gotsx.Splice(" + strings.Join(as, ", ") + ")"
		case "includes":
			return "gotsx.Includes(" + recv + ", " + g.conv(x.Args[0], r.Elem) + ")"
		case "indexOf":
			return "gotsx.IndexOf(" + recv + ", " + g.conv(x.Args[0], r.Elem) + ")"
		case "join":
			sep := `","`
			if len(x.Args) > 0 {
				sep = arg(0)
			}
			if isString(r.Elem) {
				return "gotsx.Join(" + recv + ", " + sep + ")"
			}
			return "gotsx.JoinAny(" + recv + ", " + sep + ")"
		case "slice":
			as := []string{"0"} // xs.slice() = 浅拷贝
			if len(x.Args) > 0 {
				as = nil
				for i := range x.Args {
					as = append(as, arg(i))
				}
			}
			return "gotsx.Slice(" + strings.Join(append([]string{recv}, as...), ", ") + ")"
		case "concat":
			return "gotsx.Concat(" + recv + ", " + arg(0) + ")"
		case "reverse":
			return "gotsx.Reverse(" + recv + ")"
		case "at":
			return "gotsx.AtWrap(" + recv + ", " + arg(0) + ")"
		case "flat":
			return "gotsx.Flat(" + recv + ")"
		case "sort":
			return "gotsx.Sort(" + recv + ", " + arg(0) + ")"
		case "reduce":
			return "gotsx.Reduce(" + recv + ", " + arg(0) + ", " + arg(1) + ")"
		}
	case *Prim:
		if r == TRegExp && name == "test" {
			return "gotsx.ReTest(" + recv + ", " + arg(0) + ")"
		}
		if r == TString {
			switch name {
			case "re_replace", "re_replaceAll":
				return "gotsx.ReReplace(" + recv + ", " + arg(0) + ", " + arg(1) + ")"
			case "re_split":
				return "gotsx.ReSplit(" + recv + ", " + arg(0) + ")"
			case "re_match":
				return "gotsx.ReMatch(" + recv + ", " + arg(0) + ")"
			case "re_search":
				return "gotsx.ReSearch(" + recv + ", " + arg(0) + ")"
			}
			switch name {
			case "toUpperCase":
				return "gotsx.Upper(" + recv + ")"
			case "toLowerCase":
				return "gotsx.Lower(" + recv + ")"
			case "trim":
				return "gotsx.Trim(" + recv + ")"
			case "trimStart":
				return "gotsx.TrimStart(" + recv + ")"
			case "trimEnd":
				return "gotsx.TrimEnd(" + recv + ")"
			case "lastIndexOf":
				return "gotsx.StrLastIndexOf(" + recv + ", " + arg(0) + ")"
			case "localeCompare":
				return "gotsx.Compare(" + recv + ", " + arg(0) + ")"
			case "toString":
				return recv
			case "at":
				return "gotsx.StrAt(" + recv + ", " + arg(0) + ")"
			case "includes":
				return "gotsx.StrIncludes(" + recv + ", " + arg(0) + ")"
			case "startsWith":
				return "gotsx.StartsWith(" + recv + ", " + arg(0) + ")"
			case "endsWith":
				return "gotsx.EndsWith(" + recv + ", " + arg(0) + ")"
			case "split":
				return "gotsx.Split(" + recv + ", " + arg(0) + ")"
			case "slice":
				as := []string{"0"}
				if len(x.Args) > 0 {
					as = nil
					for i := range x.Args {
						as = append(as, arg(i))
					}
				}
				return "gotsx.StrSlice(" + strings.Join(append([]string{recv}, as...), ", ") + ")"
			case "replace":
				return "gotsx.Replace(" + recv + ", " + arg(0) + ", " + arg(1) + ")"
			case "replaceAll":
				return "gotsx.ReplaceAll(" + recv + ", " + arg(0) + ", " + arg(1) + ")"
			case "repeat":
				return "gotsx.Repeat(" + recv + ", " + arg(0) + ")"
			case "indexOf":
				return "gotsx.StrIndexOf(" + recv + ", " + arg(0) + ")"
			case "charAt":
				return "gotsx.CharAt(" + recv + ", " + arg(0) + ")"
			case "padStart":
				p := `" "`
				if len(x.Args) > 1 {
					p = arg(1)
				}
				return "gotsx.PadStart(" + recv + ", " + arg(0) + ", " + p + ")"
			case "padEnd":
				p := `" "`
				if len(x.Args) > 1 {
					p = arg(1)
				}
				return "gotsx.PadEnd(" + recv + ", " + arg(0) + ", " + p + ")"
			}
		}
		if r == TNumber && name == "toString" {
			return "gotsx.Num(" + recv + ")"
		}
		if r == TNumber && name == "toFixed" {
			d := "0"
			if len(x.Args) > 0 {
				d = arg(0)
			}
			return "gotsx.ToFixed(" + recv + ", " + d + ")"
		}
	case *GlobalT:
		var args []string
		for i := range x.Args {
			args = append(args, arg(i))
		}
		switch r.Name {
		case "console":
			return "gotsx.Log(" + strings.Join(args, ", ") + ")"
		case "JSON":
			if name == "stringify" {
				return "gotsx.JSON(" + arg(0) + ")"
			}
		case "Math":
			switch name {
			case "max", "min", "floor", "ceil", "round", "abs":
				return "gotsx." + strings.ToUpper(name[:1]) + name[1:] + "(" + strings.Join(args, ", ") + ")"
			case "random":
				return "gotsx.Random()"
			case "sqrt":
				return "gotsx.Sqrt(" + arg(0) + ")"
			case "pow":
				return "gotsx.Pow(" + arg(0) + ", " + arg(1) + ")"
			case "sign":
				return "gotsx.Sign(" + arg(0) + ")"
			case "trunc":
				return "gotsx.Trunc(" + arg(0) + ")"
			}
		case "Date":
			switch name {
			case "now":
				return "gotsx.Now()"
			case "parse":
				return "gotsx.DateParse(" + arg(0) + ")"
			}
		case "Object":
			switch name {
			case "keys":
				return "gotsx.ObjectKeys(" + arg(0) + ")"
			case "values":
				return "gotsx.ObjectValues(" + arg(0) + ")"
			case "hasOwn":
				return "gotsx.HasKey(" + arg(0) + ", " + arg(1) + ")"
			}
		}
	}
	g.fail(x.Pos, "Go backend: %s.%s is not supported", rt, name)
	return ""
}

func (g *goGen) binary(x *Binary) string {
	t := x.T()
	switch x.Op {
	case "&&":
		if isNode(t) {
			fn := "gotsx.IfPlain"
			if x.Reactive {
				fn = "gotsx.If"
			}
			return fn + "(" + g.truthy(x.L) + ", func() gotsx.Node { return " + g.toNode(x.R, false) + " })"
		}
		if isBool(t) {
			return "(" + g.truthy(x.L) + " && " + g.truthy(x.R) + ")"
		}
		return fmt.Sprintf("func() %s { if !(%s) { return %s }; return %s }()", g.goType(t), g.truthy(x.L), g.zero(t), g.conv(x.R, t))
	case "||", "??":
		switch {
		case isString(t):
			return "gotsx.Or(" + g.expr(x.L) + ", " + g.conv(x.R, t) + ")"
		case isNumber(t):
			return "gotsx.OrNum(" + g.expr(x.L) + ", " + g.conv(x.R, t) + ")"
		case isBool(t):
			return "(" + g.truthy(x.L) + " || " + g.truthy(x.R) + ")"
		case isNode(t):
			return fmt.Sprintf("func() gotsx.Node { if l := %s; l != nil { return l }; return %s }()", g.toNode(x.L, false), g.toNode(x.R, false))
		}
		return fmt.Sprintf("func() %s { l := %s; if %s { return l }; return %s }()", g.goType(t), g.expr(x.L), g.truthyOf(x.L.T(), "l"), g.conv(x.R, t))
	case "+":
		if isString(t) {
			return "(" + g.strOf(x.L) + " + " + g.strOf(x.R) + ")"
		}
		return "(" + g.expr(x.L) + " + " + g.expr(x.R) + ")"
	case "-", "*", "/":
		return "(" + g.expr(x.L) + " " + x.Op + " " + g.expr(x.R) + ")"
	case "%":
		return "gotsx.Mod(" + g.expr(x.L) + ", " + g.expr(x.R) + ")"
	case "===", "==":
		if z := g.zeroCheck(x); z != "" {
			return z
		}
		return "(" + g.expr(x.L) + " == " + g.conv(x.R, x.L.T()) + ")"
	case "!==", "!=":
		if z := g.zeroCheck(x); z != "" {
			return "!" + z
		}
		return "(" + g.expr(x.L) + " != " + g.conv(x.R, x.L.T()) + ")"
	default:
		return "(" + g.expr(x.L) + " " + x.Op + " " + g.expr(x.R) + ")"
	}
}

// zeroCheck: obj === undefined / null 对复合类型比较零值(结构体含切片时 == 不能编译)
func (g *goGen) zeroCheck(x *Binary) string {
	other := x.L
	if _, ok := x.L.(*NullLit); ok {
		other = x.R
	} else if _, ok := x.R.(*NullLit); !ok {
		return ""
	}
	switch unopt(other.T()).(type) {
	case *ObjT, *ArrT, *MapT, *FnT:
		return "gotsx.IsZero(" + g.expr(other) + ")"
	}
	return ""
}

func (g *goGen) truthyOf(t Type, v string) string {
	if o, ok := t.(*OptT); ok {
		if _, isObj := o.Elem.(*ObjT); isObj {
			return "gotsx.NonZero(" + v + ")"
		}
	}
	switch unopt(t) {
	case TString:
		return v + ` != ""`
	case TNumber:
		return v + " != 0"
	case TBool:
		return v
	}
	return "gotsx.Truthy(" + v + ")"
}

func (g *goGen) arrow(x *Arrow) string {
	ft, _ := x.T().(*FnT)
	if ft == nil {
		g.fail(x.Pos, "arrow function type is unknown")
	}
	var ps []string
	for i, p := range x.Params {
		name := "p" + strconv.Itoa(i)
		if p.Pat.Kind == PatIdent {
			name = p.Pat.Sym.Go
		}
		ps = append(ps, name+" "+g.goType(ft.Params[i].Type))
	}
	var bodyNode any = x.ExprBody
	if x.Body != nil {
		bodyNode = x.Body.Stmts
	}
	if x.Async || clientOnly(bodyNode) { // 只进 JS 后端; Go 里留一个同类型的空壳
		return g.stub(ft, ps)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "func(%s) %s {\n", strings.Join(ps, ", "), g.goType(ft.Ret))
	sub := &goGen{c: g.c, m: g.m, ind: g.ind + 1, hostPkg: g.hostPkg, tmp: g.tmp, curRet: ft.Ret}
	for i, p := range x.Params {
		if p.Pat.Kind != PatIdent {
			sub.bindParam(p.Pat, "p"+strconv.Itoa(i), ft.Params[i].Type)
		} else {
			sub.line("_ = %s", p.Pat.Sym.Go)
		}
	}
	if x.ExprBody != nil {
		switch {
		case ft.Ret == nil || ft.Ret == TVoid:
			sub.exprStmt(x.ExprBody)
		case isNode(ft.Ret):
			sub.line("return %s", sub.toNode(x.ExprBody, false))
		default:
			sub.line("return %s", sub.conv(x.ExprBody, ft.Ret))
		}
	} else {
		sub.stmts(x.Body.Stmts)
	}
	g.tmp = sub.tmp
	if sub.needHost {
		g.needHost = true
	}
	b.WriteString(sub.b.String())
	b.WriteString(strings.Repeat("\t", g.ind) + "}")
	return b.String()
}

// ---------- JSX ----------

// toNode: 任意子节点表达式 → gotsx.Node 表达式
func (g *goGen) toNode(e Expr, reactive bool) string {
	switch x := e.(type) {
	case *JSXElem:
		return g.jsxElem(x)
	case *JSXFrag:
		return g.childrenNode(x.Children)
	case *JSXText:
		s := normalizeJSXText(x.Text)
		if s == "" {
			return "nil"
		}
		return "gotsx.Text(" + strconv.Quote(s) + ")"
	case *JSXExprChild:
		if x.X == nil {
			return "nil"
		}
		return g.toNode(x.X, x.Reactive)
	case *Paren:
		return g.toNode(x.X, reactive)
	case *NullLit, *BoolLit:
		return "nil"
	}
	t := unopt(e.T())
	switch tt := t.(type) {
	case *Prim:
		switch tt {
		case TNode:
			return g.expr(e)
		case TString:
			if reactive {
				return "gotsx.Dyn(" + g.expr(e) + ")"
			}
			return "gotsx.Text(" + g.expr(e) + ")"
		case TNumber:
			if reactive {
				return "gotsx.Dyn(gotsx.Num(" + g.expr(e) + "))"
			}
			return "gotsx.Text(gotsx.Num(" + g.expr(e) + "))"
		case TBool, TUndef, TVoid:
			return "nil"
		}
		return "gotsx.Text(gotsx.Str(" + g.expr(e) + "))"
	case *ArrT:
		if isNode(tt.Elem) {
			if reactive {
				return "gotsx.Nodes(" + g.expr(e) + ")"
			}
			return "gotsx.NodesPlain(" + g.expr(e) + ")"
		}
		return "gotsx.Text(gotsx.JoinAny(" + g.expr(e) + `, ""))`
	}
	g.fail(e.GetPos(), "cannot use %s as a JSX child", t)
	return ""
}

func (g *goGen) children(kids []Expr) string {
	var out []string
	for _, k := range kids {
		if t, ok := k.(*JSXText); ok && normalizeJSXText(t.Text) == "" {
			continue
		}
		if ec, ok := k.(*JSXExprChild); ok && ec.X == nil {
			continue
		}
		out = append(out, g.toNode(k, false))
	}
	return strings.Join(out, ", ")
}

func (g *goGen) jsxElem(x *JSXElem) string {
	if x.Comp != nil && x.Comp.Go == "gotsx.Suspense" {
		// 边界: fallback 立即求值进外壳, children 包进 thunk —— 里面的宿主调用在外壳发出后才跑
		fb := "nil"
		for _, a := range x.Attrs {
			if a.Name == "fallback" && a.Val != nil {
				fb = g.toNode(a.Val, false)
			}
		}
		return "gotsx.Suspense(" + fb + ", func() gotsx.Node { return " + g.childrenNode(x.Children) + " })"
	}
	if x.Comp != nil {
		comp := x.Comp.Comp
		var fs []string
		for _, a := range x.Attrs {
			if a.Name == "key" {
				continue
			}
			f := comp.Props.Field(a.Name)
			if a.Val == nil {
				fs = append(fs, f.Go+": true")
				continue
			}
			fs = append(fs, f.Go+": "+g.conv(a.Val, f.Type))
		}
		if len(x.Children) > 0 {
			fs = append(fs, "Children: "+g.childrenNode(x.Children))
		}
		ctxArg := ""
		if x.Comp.Module != nil && x.Comp.Module.Kind == "client" && x.Comp != x.Comp.Module.Default { // a helper component of a client module takes the render context (islands wrap it themselves)
			ctxArg = "_ctx, "
		}
		return x.Comp.Go + "(" + ctxArg + comp.Props.GoName + "{" + strings.Join(fs, ", ") + "})"
	}
	w := &htmlWriter{g: g}
	w.elem(x)
	return w.closure()
}

// ---------- 流式写入: 元素编成对 _ctx 的顺序写入, 静态 HTML 合并成一个字符串(templ 的做法), 每个组件只有一个闭包 ----------

var voidTags = map[string]bool{"area": true, "base": true, "br": true, "col": true, "embed": true, "hr": true, "img": true, "input": true, "link": true, "meta": true, "source": true, "track": true, "wbr": true}

type htmlWriter struct {
	g     *goGen
	raw   strings.Builder // 待写出的静态 HTML(编译期已转义)
	stmts []string
}

func (w *htmlWriter) text(s string) { w.raw.WriteString(s) }
func (w *htmlWriter) flush() {
	if w.raw.Len() > 0 {
		w.stmts = append(w.stmts, "_ctx.W("+strconv.Quote(w.raw.String())+")")
		w.raw.Reset()
	}
}
func (w *htmlWriter) stmt(s string) {
	w.flush()
	w.stmts = append(w.stmts, s)
}

// closure: 收尾成一个 gotsx.Node 字面量
func (w *htmlWriter) closure() string {
	w.flush()
	if len(w.stmts) == 0 {
		return "gotsx.Node(nil)"
	}
	ind := strings.Repeat("\t", w.g.ind+1)
	return "func(_ctx *gotsx.Ctx) {\n" + ind + strings.Join(w.stmts, "\n"+ind) + "\n" + strings.Repeat("\t", w.g.ind) + "}"
}

func (w *htmlWriter) elem(x *JSXElem) {
	if x.Comp != nil {
		w.stmt("_ctx.N(" + w.g.jsxElem(x) + ")")
		return
	}
	g := w.g
	w.text("<" + x.Tag)
	for _, a := range x.Attrs {
		if a.Name == "key" || strings.HasPrefix(a.Name, "on") || a.Name == "dangerouslySetInnerHTML" {
			continue
		}
		if a.Val == nil {
			w.text(" " + a.Name)
			continue
		}
		if s, ok := a.Val.(*StrLit); ok {
			w.text(" " + a.Name + `="` + html.EscapeString(s.Val) + `"`)
			continue
		}
		name := strconv.Quote(a.Name)
		vt := unopt(a.Val.T())
		switch {
		case isBool(vt) && (strings.HasPrefix(a.Name, "aria-") || strings.HasPrefix(a.Name, "data-")):
			w.stmt("_ctx.Attr(" + name + ", gotsx.Str(" + g.expr(a.Val) + "))")
		case isBool(vt):
			w.stmt("if " + g.expr(a.Val) + " {\n\t\t_ctx.W(" + strconv.Quote(" "+a.Name) + ")\n\t}")
		case isNumber(vt):
			w.stmt("_ctx.Attr(" + name + ", gotsx.Num(" + g.expr(a.Val) + "))")
		case isString(vt):
			w.stmt("_ctx.Attr(" + name + ", " + g.expr(a.Val) + ")")
		default:
			w.stmt("_ctx.Attr(" + name + ", gotsx.Str(" + g.expr(a.Val) + "))")
		}
	}
	w.text(">")
	if voidTags[x.Tag] {
		return
	}
	w.kids(x.Children)
	if x.Tag == "head" || x.Tag == "body" {
		w.stmt("_ctx.Close(" + strconv.Quote(x.Tag) + ")")
	} else {
		w.text("</" + x.Tag + ">")
	}
}

func (w *htmlWriter) kids(kids []Expr) {
	for _, k := range kids {
		switch x := k.(type) {
		case *JSXText:
			w.text(html.EscapeString(normalizeJSXText(x.Text)))
		case *JSXExprChild:
			if x.X != nil {
				w.child(x.X, x.Reactive)
			}
		default:
			w.child(k, false)
		}
	}
}

// child: 子节点位置的表达式 —— JSX 继续内联, 文本就地转义, 其它节点表达式调用
func (w *htmlWriter) child(e Expr, reactive bool) {
	g := w.g
	for {
		p, ok := e.(*Paren)
		if !ok {
			break
		}
		e = p.X
	}
	switch x := e.(type) {
	case *JSXElem:
		w.elem(x)
		return
	case *JSXFrag:
		w.kids(x.Children)
		return
	case *JSXText:
		w.text(html.EscapeString(normalizeJSXText(x.Text)))
		return
	case *NullLit, *BoolLit:
		return
	case *StrLit:
		w.text(html.EscapeString(x.Val))
		return
	}
	if w.inlineMap(e, reactive) {
		return
	}
	t := unopt(e.T())
	switch tt := t.(type) {
	case *Prim:
		switch tt {
		case TNode:
			w.stmt("_ctx.N(" + g.expr(e) + ")")
		case TString:
			if reactive {
				w.stmt("_ctx.Dyn(" + g.expr(e) + ")")
			} else {
				w.stmt("_ctx.Esc(" + g.expr(e) + ")")
			}
		case TNumber:
			if reactive {
				w.stmt("_ctx.Dyn(gotsx.Num(" + g.expr(e) + "))")
			} else {
				w.stmt("_ctx.Esc(gotsx.Num(" + g.expr(e) + "))")
			}
		case TBool, TUndef, TVoid:
		default:
			w.stmt("_ctx.Esc(gotsx.Str(" + g.expr(e) + "))")
		}
		return
	case *ArrT:
		if isNode(tt.Elem) {
			if reactive {
				w.stmt("gotsx.Nodes(" + g.expr(e) + ")(_ctx)")
			} else {
				w.stmt("gotsx.NodesPlain(" + g.expr(e) + ")(_ctx)")
			}
		} else {
			w.stmt("_ctx.Esc(gotsx.JoinAny(" + g.expr(e) + `, ""))`)
		}
		return
	}
	g.fail(e.GetPos(), "cannot use %s as a JSX child", t)
}

// inlineMap: {xs.map((x) => <li>…</li>)} 直接编成 for 循环写入, 不构造 []Node 和每项的闭包。
// 只处理箭头函数是表达式体(或只有一个 return)且参数是普通标识符的情况; 其它走通用路径。
func (w *htmlWriter) inlineMap(e Expr, reactive bool) bool {
	call, ok := e.(*Call)
	if !ok || call.Kind != "builtin:map" || len(call.Args) != 1 {
		return false
	}
	m, ok := call.Fn.(*Member)
	if !ok {
		return false
	}
	if at, ok := unopt(call.T()).(*ArrT); !ok || !isNode(at.Elem) {
		return false
	}
	if _, ok := unopt(m.X.T()).(*ArrT); !ok {
		return false
	}
	a, ok := call.Args[0].(*Arrow)
	if !ok || a.Async || len(a.Params) > 2 {
		return false
	}
	body := a.ExprBody
	if body == nil {
		if a.Body == nil || len(a.Body.Stmts) != 1 {
			return false
		}
		r, ok := a.Body.Stmts[0].(*ReturnStmt)
		if !ok || r.X == nil {
			return false
		}
		body = r.X
	}
	for _, p := range a.Params {
		if p.Pat.Kind != PatIdent {
			return false
		}
	}
	g := w.g
	if reactive {
		w.stmt("_ctx.ListStart()")
	}
	item := "_"
	if len(a.Params) >= 1 {
		item = a.Params[0].Pat.Sym.Go
	}
	switch {
	case len(a.Params) == 2:
		idx := a.Params[1].Pat.Sym.Go
		w.stmt("for _i, " + item + " := range " + g.expr(m.X) + " {")
		w.stmt("\t" + idx + " := float64(_i)")
		w.stmt("\t_ = " + idx)
		w.stmt("\t_ = " + item)
	case len(a.Params) == 1:
		w.stmt("for _, " + item + " := range " + g.expr(m.X) + " {")
		w.stmt("\t_ = " + item)
	default: // () => <Skeleton />: 只按长度重复
		w.stmt("for range " + g.expr(m.X) + " {")
	}
	inner := &htmlWriter{g: g}
	inner.child(body, false)
	inner.flush()
	for _, s := range inner.stmts {
		w.stmt("\t" + s)
	}
	w.stmt("}")
	if reactive {
		w.stmt("_ctx.ListEnd()")
	}
	return true
}

// childrenNode: 一组子节点 → 一个 Node(组件的 children / fragment)
func (g *goGen) childrenNode(kids []Expr) string {
	w := &htmlWriter{g: g}
	w.kids(kids)
	return w.closure()
}

// JSX 文本的空白规则(与 React/Babel 一致): 多行时按行 trim, 空行丢弃, 用单个空格拼接
func normalizeJSXText(s string) string {
	if !strings.Contains(s, "\n") {
		return s
	}
	lines := strings.Split(s, "\n")
	var out []string
	for i, ln := range lines {
		ln = strings.ReplaceAll(ln, "\t", " ")
		if i != 0 {
			ln = strings.TrimLeft(ln, " \r")
		}
		if i != len(lines)-1 {
			ln = strings.TrimRight(ln, " \r")
		}
		if ln != "" {
			out = append(out, ln)
		}
	}
	return strings.Join(out, " ")
}

// walkExpr: 深度优先遍历(f 返回 false 不再深入)
func walkExpr(e Expr, f func(Expr) bool) {
	if e == nil || !f(e) {
		return
	}
	switch x := e.(type) {
	case *TemplateLit:
		for _, a := range x.Exprs {
			walkExpr(a, f)
		}
	case *ArrayLit:
		for _, a := range x.Elems {
			walkExpr(a, f)
		}
	case *ObjectLit:
		for _, p := range x.Props {
			walkExpr(p.Val, f)
			walkExpr(p.Spread, f)
		}
	case *Member:
		walkExpr(x.X, f)
	case *Index:
		walkExpr(x.X, f)
		walkExpr(x.I, f)
	case *Call:
		walkExpr(x.Fn, f)
		for _, a := range x.Args {
			walkExpr(a, f)
		}
	case *Unary:
		walkExpr(x.X, f)
	case *Binary:
		walkExpr(x.L, f)
		walkExpr(x.R, f)
	case *CondExpr:
		walkExpr(x.Test, f)
		walkExpr(x.Then, f)
		walkExpr(x.Else, f)
	case *Arrow:
		walkExpr(x.ExprBody, f)
	case *Assign:
		walkExpr(x.Target, f)
		walkExpr(x.Val, f)
	case *Update:
		walkExpr(x.X, f)
	case *AsExpr:
		walkExpr(x.X, f)
	case *AwaitExpr:
		walkExpr(x.X, f)
	case *SpreadExpr:
		walkExpr(x.X, f)
	case *NonNull:
		walkExpr(x.X, f)
	case *Paren:
		walkExpr(x.X, f)
	case *JSXElem:
		for _, a := range x.Attrs {
			walkExpr(a.Val, f)
		}
		for _, k := range x.Children {
			walkExpr(k, f)
		}
	case *JSXFrag:
		for _, k := range x.Children {
			walkExpr(k, f)
		}
	case *JSXExprChild:
		walkExpr(x.X, f)
	}
}
